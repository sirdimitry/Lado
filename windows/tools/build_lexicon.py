#!/usr/bin/env python3
"""Build the compact C++ lexicon from the shared Python data file.

Input:  src/lado/data/frequencies.json.gz  (the macOS engine's dictionary)
Output: windows/data/lexicon.bin           (little-endian, UTF-16 words)

Layout:
    "LADOLEX1"                       8 bytes magic
    uint32 format version            = 1
    uint16 table count               = 2
    per table:
        uint16 code length, bytes    "en" / "ru"
        uint32 entry count
        entries sorted by key:
            uint16 unit count, UTF-16LE units (casefolded)
            float32 score            (raw score / 100, as in engine.py)

The script prints a checksum so a rebuild can be compared with the committed
artifact. It never downloads anything.
"""
from __future__ import annotations

import gzip
import hashlib
import json
import struct
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
SOURCE = ROOT / "src" / "lado" / "data" / "frequencies.json.gz"
OUTPUT = Path(__file__).resolve().parents[1] / "data" / "lexicon.bin"
REPORT = OUTPUT.with_suffix(".txt")
MAGIC = b"LADOLEX1"
VERSION = 1
MAX_UNITS = 255


def build_table(scores: dict[str, float]) -> list[tuple[str, float]]:
    merged: dict[str, float] = {}
    for word, value in scores.items():
        if not isinstance(word, str) or not word:
            continue
        key = word.casefold()
        units = len(key.encode("utf-16-le")) // 2
        if units == 0 or units > MAX_UNITS:
            continue
        number = float(value)
        if not number > 0:
            continue
        merged[key] = max(merged.get(key, 0.0), number)
    return sorted(merged.items(), key=lambda item: item[0])


def main() -> int:
    data = json.loads(gzip.decompress(SOURCE.read_bytes()))
    tables = {"en": data["scores"]["en"], "ru": data["scores"]["ru"]}

    payload = bytearray()
    payload += MAGIC
    payload += struct.pack("<I", VERSION)
    payload += struct.pack("<H", len(tables))
    counts = {}
    for code, scores in tables.items():
        entries = build_table(scores)
        counts[code] = len(entries)
        encoded = code.encode("ascii")
        payload += struct.pack("<H", len(encoded)) + encoded
        payload += struct.pack("<I", len(entries))
        for word, value in entries:
            units = word.encode("utf-16-le")
            unit_count = len(units) // 2
            payload += struct.pack("<H", unit_count) + units
            payload += struct.pack("<f", value / 100.0)

    OUTPUT.parent.mkdir(parents=True, exist_ok=True)
    OUTPUT.write_bytes(bytes(payload))

    digest = hashlib.sha256(payload).hexdigest()
    lines = [
        "Generated by windows/tools/build_lexicon.py from",
        "src/lado/data/frequencies.json.gz. Do not edit by hand.",
        f"format: {VERSION}",
        f"bytes: {len(payload)}",
        f"sha256: {digest}",
    ]
    for code, count in counts.items():
        lines.append(f"{code}: {count} words")
    REPORT.write_text("\n".join(lines) + "\n", encoding="utf-8")

    print("\n".join(lines))
    return 0


if __name__ == "__main__":
    sys.exit(main())
